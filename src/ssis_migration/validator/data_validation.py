"""
Data validation framework for SSIS-to-Databricks migrations.

Generates Spark SQL validation queries that compare source
(SQL Server staging tables) and target (Databricks dimension/fact
tables) data after migration.

Validation checks:
  1. Row count comparison (staging vs target)
  2. Column completeness (all expected columns present)
  3. Null checks (non-nullable columns have no nulls)
  4. Key uniqueness (no duplicate primary keys)
  5. Checksum/hash comparison between staging and target
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any


@dataclass
class ValidationQuery:
    """A single validation query with metadata."""

    query_id: str
    step_id: str
    check_type: str
    description: str
    sql: str
    expected_result: str = ""
    table: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "query_id": self.query_id,
            "step_id": self.step_id,
            "check_type": self.check_type,
            "description": self.description,
            "sql": self.sql,
            "expected_result": self.expected_result,
            "table": self.table,
        }


@dataclass
class ValidationReport:
    """A complete validation report for a migration."""

    package_name: str
    queries: list[ValidationQuery] = field(default_factory=list)
    table_mappings: list[dict[str, str]] = field(default_factory=list)
    summary: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "package_name": self.package_name,
            "queries": [q.to_dict() for q in self.queries],
            "table_mappings": self.table_mappings,
            "summary": self.summary,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent)


class DataValidator:
    """
    Generate data validation queries from a migration plan
    and database metadata.
    """

    def generate(
        self,
        plan: dict[str, Any],
        source_metadata: dict[str, Any],
        target_metadata: dict[str, Any],
        *,
        catalog: str = "main",
        schema: str = "default",
    ) -> ValidationReport:
        """Build a ValidationReport from the migration plan."""
        package_name = plan.get("package_name", "Unknown")

        target_tables = self._index_tables(target_metadata)
        source_tables = self._index_tables(source_metadata)

        table_mappings = self._build_table_mappings(
            plan, target_tables, source_tables,
        )

        queries: list[ValidationQuery] = []

        for mapping in table_mappings:
            step_id = mapping["step_id"]
            staging_table = mapping.get("staging_table", "")
            target_table = mapping.get("target_table", "")
            target_cols = mapping.get("target_columns", [])
            staging_cols = mapping.get("staging_columns", [])

            if not target_table:
                continue

            fq_target = self._qualify(target_table, catalog, schema)
            fq_staging = self._qualify(staging_table, catalog, schema)

            queries.append(self._row_count_query(
                step_id, fq_target,
            ))

            queries.append(self._column_coverage_query(
                step_id, fq_target, target_cols,
            ))

            queries.extend(self._null_check_queries(
                step_id, fq_target, target_cols,
            ))

            key_cols = [
                c["name"] for c in target_cols
                if c.get("is_primary_key")
                or (c.get("nullable") is False
                    and c.get("ordinal") == 1)
            ]
            if not key_cols and target_cols:
                key_cols = [target_cols[0]["name"]]

            queries.append(self._key_uniqueness_query(
                step_id, fq_target, key_cols,
            ))

            if staging_table and staging_cols:
                queries.append(self._checksum_query(
                    step_id, fq_staging, fq_target,
                    staging_cols, target_cols,
                ))

        summary = {
            "total_checks": len(queries),
            "check_types": list(
                {q.check_type for q in queries}
            ),
            "table_count": len(table_mappings),
            "tables_validated": [
                m["target_table"]
                for m in table_mappings
                if m.get("target_table")
            ],
        }

        return ValidationReport(
            package_name=package_name,
            queries=queries,
            table_mappings=table_mappings,
            summary=summary,
        )

    def generate_sql_file(self, report: ValidationReport) -> str:
        """Generate a Spark SQL file with all validation queries."""
        lines: list[str] = [
            f"-- Data Validation for {report.package_name}",
            "-- Generated by ssis-migration-agent",
            f"-- Total checks: {report.summary.get('total_checks', 0)}",
            "",
            "-- ============================================",
            "-- Table Mappings",
            "-- ============================================",
        ]
        for m in report.table_mappings:
            lines.append(
                f"-- {m['step_id']}:\n"
                f"--   staging: {m.get('staging_table', 'N/A')}\n"
                f"--   target:  {m.get('target_table', 'N/A')}"
            )
        lines.append("")
        lines.append(
            "-- ============================================\n"
            "-- Validation Queries\n"
            "-- ============================================"
        )
        for q in report.queries:
            lines.append("")
            lines.append(
                f"-- [{q.query_id}] {q.check_type}: {q.description}"
            )
            if q.expected_result:
                lines.append(f"-- Expected: {q.expected_result}")
            lines.append(q.sql)
            lines.append(";")
        return "\n".join(lines)

    def generate_notebook(self, report: ValidationReport) -> dict[str, Any]:
        """Generate a Databricks notebook with validation queries."""
        cells: list[dict[str, Any]] = []
        cells.append(self._md_cell(
            f"# Data Validation \u2014 {report.package_name}\n\n"
            f"| Field | Value |\n| --- | --- |\n"
            f"| Total Checks | {report.summary.get('total_checks', 0)} |\n"
            f"| Tables Validated | {report.summary.get('table_count', 0)} |\n"
            f"| Check Types | {', '.join(report.summary.get('check_types', []))} |\n"
        ))
        by_step: dict[str, list[ValidationQuery]] = {}
        for q in report.queries:
            by_step.setdefault(q.step_id, []).append(q)
        for step_id, step_queries in by_step.items():
            cells.append(self._md_cell(
                f"## {step_id}\n{len(step_queries)} validation checks"
            ))
            for q in step_queries:
                cells.append(self._md_cell(
                    f"**{q.check_type}**: {q.description}"
                ))
                cells.append(self._code_cell(f"%sql\n{q.sql};"))
        return {
            "nbformat": 4,
            "nbformat_minor": 5,
            "metadata": {
                "application/databricks": {
                    "name": f"{report.package_name}_Data_Validation",
                    "language": "python",
                },
            },
            "cells": cells,
        }

    # -------------------------------------------------
    # Query builders
    # -------------------------------------------------

    def _row_count_query(self, step_id: str, table: str) -> ValidationQuery:
        return ValidationQuery(
            query_id=f"{step_id}_row_count",
            step_id=step_id,
            check_type="row_count",
            description=f"Row count for {table}",
            sql=f"SELECT COUNT(*) AS row_count FROM {table}",
            expected_result="row_count > 0",
            table=table,
        )

    def _column_coverage_query(
        self, step_id: str, table: str,
        columns: list[dict[str, Any]],
    ) -> ValidationQuery:
        col_names = [c["name"] for c in columns]
        col_list = ", ".join(f"'{c}'" for c in col_names)
        tbl_short = table.split(".")[-1] if "." in table else table
        return ValidationQuery(
            query_id=f"{step_id}_column_coverage",
            step_id=step_id,
            check_type="column_coverage",
            description=(
                f"Verify {len(col_names)} expected columns exist in {table}"
            ),
            sql=(
                f"SELECT count(*) AS missing_columns\n"
                f"FROM (\n"
                f"  SELECT column_name\n"
                f"  FROM information_schema.columns\n"
                f"  WHERE table_name = '{tbl_short}'\n"
                f"  AND column_name NOT IN ({col_list})\n"
                f") t"
            ),
            expected_result="missing_columns = 0",
            table=table,
        )

    def _null_check_queries(
        self, step_id: str, table: str,
        columns: list[dict[str, Any]],
    ) -> list[ValidationQuery]:
        queries = []
        for col in columns:
            if col.get("nullable") is False:
                col_name = col["name"]
                queries.append(ValidationQuery(
                    query_id=f"{step_id}_null_{col_name}",
                    step_id=step_id,
                    check_type="null_check",
                    description=(
                        f"No nulls in non-nullable column {col_name} of {table}"
                    ),
                    sql=(
                        f"SELECT COUNT(*) AS null_count\n"
                        f"FROM {table}\n"
                        f"WHERE {col_name} IS NULL"
                    ),
                    expected_result="null_count = 0",
                    table=table,
                ))
        return queries

    def _key_uniqueness_query(
        self, step_id: str, table: str,
        key_columns: list[str],
    ) -> ValidationQuery:
        if not key_columns:
            return ValidationQuery(
                query_id=f"{step_id}_key_unique",
                step_id=step_id,
                check_type="key_uniqueness",
                description=f"No key columns identified for {table}",
                sql=f"-- No key columns identified for {table}",
                expected_result="N/A",
                table=table,
            )
        key_list = ", ".join(key_columns)
        return ValidationQuery(
            query_id=f"{step_id}_key_unique",
            step_id=step_id,
            check_type="key_uniqueness",
            description=(
                f"No duplicate keys in {table} (keys: {key_list})"
            ),
            sql=(
                f"SELECT {key_list}, COUNT(*) AS dup_count\n"
                f"FROM {table}\n"
                f"GROUP BY {key_list}\n"
                f"HAVING COUNT(*) > 1"
            ),
            expected_result="0 rows returned",
            table=table,
        )

    def _checksum_query(
        self, step_id: str, staging_table: str,
        target_table: str,
        staging_cols: list[dict[str, Any]],
        target_cols: list[dict[str, Any]],
    ) -> ValidationQuery:
        staging_names = {c["name"] for c in staging_cols}
        target_names = {c["name"] for c in target_cols}
        common = sorted(staging_names & target_names)
        if not common:
            return ValidationQuery(
                query_id=f"{step_id}_checksum",
                step_id=step_id,
                check_type="checksum",
                description=(
                    f"No common columns between {staging_table} and {target_table}"
                ),
                sql=(
                    f"-- No common columns between {staging_table} and {target_table}"
                ),
                expected_result="N/A",
            )
        hash_cols = ", ".join(
            f"COALESCE(CAST({c} AS STRING), '')" for c in common
        )
        return ValidationQuery(
            query_id=f"{step_id}_checksum",
            step_id=step_id,
            check_type="checksum",
            description=(
                f"Checksum comparison: {staging_table} vs {target_table}"
            ),
            sql=(
                f"WITH staging_hash AS (\n"
                f"  SELECT SUM(HASH({hash_cols})) AS checksum\n"
                f"  FROM {staging_table}\n"
                f"),\n"
                f"target_hash AS (\n"
                f"  SELECT SUM(HASH({hash_cols})) AS checksum\n"
                f"  FROM {target_table}\n"
                f")\n"
                f"SELECT\n"
                f"  s.checksum AS staging_checksum,\n"
                f"  t.checksum AS target_checksum,\n"
                f"  (s.checksum = t.checksum) AS checksums_match\n"
                f"FROM staging_hash s, target_hash t"
            ),
            expected_result="checksums_match = true",
        )

    # -------------------------------------------------
    # Helpers
    # -------------------------------------------------

    @staticmethod
    def _index_tables(metadata: dict[str, Any]) -> dict[str, dict[str, Any]]:
        result = {}
        for t in metadata.get("tables", []):
            key = f"{t['schema']}.{t['name']}"
            result[key] = t
        return result

    def _build_table_mappings(
        self, plan: dict[str, Any],
        target_tables: dict[str, dict[str, Any]],
        source_tables: dict[str, dict[str, Any]],
    ) -> list[dict[str, str]]:
        mappings = []
        for step in plan.get("steps", []):
            step_id = step["step_id"]
            step_type = step.get("step_type", "")
            target_objects = step.get("target_objects", [])
            staging_table = target_objects[0] if target_objects else ""
            target_table = self._derive_target_table(
                step_id, step_type, target_tables,
            )
            staging_cols = []
            if staging_table and staging_table in target_tables:
                staging_cols = target_tables[staging_table].get("columns", [])
            elif staging_table and staging_table in source_tables:
                staging_cols = source_tables[staging_table].get("columns", [])
            target_cols = []
            if target_table and target_table in target_tables:
                target_cols = target_tables[target_table].get("columns", [])
            mappings.append({
                "step_id": step_id,
                "step_type": step_type,
                "staging_table": staging_table,
                "target_table": target_table,
                "staging_columns": staging_cols,
                "target_columns": target_cols,
            })
        return mappings

    @staticmethod
    def _derive_target_table(
        step_id: str, step_type: str,
        target_tables: dict[str, dict[str, Any]],
    ) -> str:
        parts = step_id.split("_")
        if len(parts) < 3:
            return ""
        type_suffix = parts[-1]
        entity_parts = parts[1:-1]
        if type_suffix == "dimension":
            schema = "Dimension"
        elif type_suffix == "fact":
            schema = "Fact"
        else:
            return ""
        entity_name = " ".join(p.capitalize() for p in entity_parts)
        full_name = f"{schema}.{entity_name}"
        if full_name in target_tables:
            return full_name
        full_name_no_space = f"{schema}.{entity_name.replace(' ', '')}"
        if full_name_no_space in target_tables:
            return full_name_no_space
        return ""

    @staticmethod
    def _qualify(table: str, catalog: str, schema: str) -> str:
        if not table:
            return table
        parts = table.split(".")
        if len(parts) == 2:
            return f"{catalog}.{parts[0]}.{parts[1]}"
        elif len(parts) == 1:
            return f"{catalog}.{schema}.{parts[0]}"
        return table

    @staticmethod
    def _md_cell(source: str) -> dict[str, Any]:
        lines = source.split("\n")
        return {
            "cell_type": "markdown",
            "metadata": {},
            "source": [line + "\n" for line in lines[:-1]] + [lines[-1]],
        }

    @staticmethod
    def _code_cell(source: str) -> dict[str, Any]:
        lines = source.split("\n")
        return {
            "cell_type": "code",
            "metadata": {},
            "source": [line + "\n" for line in lines[:-1]] + [lines[-1]],
            "outputs": [],
            "execution_count": None,
        }